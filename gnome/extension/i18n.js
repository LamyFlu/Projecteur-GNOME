export function createTranslator(languages = GLib.get_language_names()) {
    const language = (languages[0] ?? 'en').toLowerCase();
    const isChinese = /^zh(?:[_\-.@]|$)/.test(language);
    return text => isChinese ? traditionalChinese[text] ?? text : text;
}
